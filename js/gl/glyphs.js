/* Lit cells of a glyph as [col, row] pairs. */
export function cells(glyph) {
  const out = [];
  for (let y = 0; y < glyph.length; y++)
    for (let x = 0; x < glyph[y].length; x++) if (glyph[y][x]) out.push([x, y]);
  return out;
}
